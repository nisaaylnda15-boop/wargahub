-- Jalankan di Supabase Dashboard > SQL Editor.
create table if not exists public.umkm (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  address text not null,
  phone text not null,
  description text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.lost_found (
  id bigint generated by default as identity primary key,
  item text not null,
  kind text not null,
  location text not null,
  phone text not null,
  description text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  location text not null,
  description text default '',
  status text not null default 'Menunggu',
  created_at timestamptz not null default now()
);

alter table public.umkm enable row level security;
alter table public.lost_found enable row level security;
alter table public.reports enable row level security;

-- Kebijakan publik untuk prototype tugas kuliah saja.
-- Semua orang dapat membaca dan menambahkan data; jangan gunakan untuk produksi tanpa autentikasi/moderasi.
create policy "public read umkm" on public.umkm for select to anon using (true);
create policy "public insert umkm" on public.umkm for insert to anon with check (true);
create policy "public read lost_found" on public.lost_found for select to anon using (true);
create policy "public insert lost_found" on public.lost_found for insert to anon with check (true);
create policy "public read reports" on public.reports for select to anon using (true);
create policy "public insert reports" on public.reports for insert to anon with check (true);

grant select, insert on public.umkm to anon;
grant select, insert on public.lost_found to anon;
grant select, insert on public.reports to anon;
grant usage, select on all sequences in schema public to anon;
